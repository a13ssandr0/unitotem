#!/usr/bin/env python3
"""Host-side test of unitotem-release `build` (layout 1) and `build-ab` (layout 2). Throwaway Ed25519 keys are
generated by the tool's own `keygen` inside a temporary directory; no real key is read. Images are synthetic
GPT disks (sparse), built with sgdisk/mke2fs/mtools. Checks manifest contents, signatures, hashes, and that the
root part restores to a slot with the expected version and label.

  python3 tools/release/test_release_build.py
"""
import hashlib, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REL = os.path.join(HERE, "unitotem-release")
ok = fail = 0


def check(name, cond, extra=""):
    global ok, fail
    if cond: ok += 1; print("PASS:", name)
    else: fail += 1; print("FAIL:", name, extra)


def sh(*cmd, check_rc=True):
    return subprocess.run(cmd, check=check_rc, capture_output=True, text=True)


def rel(*args):
    """Run the release CLI; returns the CompletedProcess without raising."""
    return subprocess.run([REL, *args], capture_output=True, text=True)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""): h.update(chunk)
    return h.hexdigest()


def verify(pub, data, sig):
    return subprocess.run(["openssl", "pkeyutl", "-verify", "-pubin", "-inkey", pub, "-rawin", "-in", data,
                           "-sigfile", sig], capture_output=True).returncode == 0


def part_bounds(img, n):
    info = sh("sgdisk", "-i", str(n), img).stdout
    first = int(next(l for l in info.splitlines() if l.startswith("First sector")).split(":")[1].split()[0])
    last = int(next(l for l in info.splitlines() if l.startswith("Last sector")).split(":")[1].split()[0])
    name = next(l for l in info.splitlines() if l.startswith("Partition name")).split("'")[1]
    return first, last, name


def make_image(td, name, version, root_label="ROOT_A", arm=False):
    """Synthetic disk: p1 FIRMWARE (FAT, slota/ boot files when arm), p2 root ext4 with release-version.
    Returns (image path, UUID of the root filesystem)."""
    img = os.path.join(td, name + ".img")
    sh("truncate", "-s", "192M", img)
    sh("sgdisk", "-Z", img)
    sh("sgdisk", "-n", "1:2048:+64M", "-t", "1:0700" if arm else "1:ef00", "-c", "1:FIRMWARE", img)
    sh("sgdisk", "-n", "2:0:+64M", "-t", "2:8300", "-c", "2:" + root_label, img)
    fat = os.path.join(td, name + "-fat.img")
    sh("mkfs.fat", "-C", "-F32", "-n", "FIRMWARE", fat, "65536")
    if arm:
        src = os.path.join(td, name + "-boot"); os.makedirs(src + "/overlays")
        files = {"kernel8.img": b"K" * 5000, "initramfs8": b"I" * 7000, "cmdline.txt": b"console=tty1 root=LABEL=ROOT_A unitotem.slot=a\n",
                 "overlays/vc4.dtbo": b"O" * 80}
        for f, c in files.items():
            with open(os.path.join(src, f), "wb") as h: h.write(c)
        sh("mmd", "-i", fat, "::slota"); sh("mmd", "-i", fat, "::slota/overlays")
        for f in files: sh("mcopy", "-i", fat, os.path.join(src, f), "::slota/" + f)
    rootdir = os.path.join(td, name + "-root")
    os.makedirs(rootdir + "/usr/share/unitotem")
    with open(rootdir + "/usr/share/unitotem/release-version", "w") as h: h.write(version + "\n")
    ext = os.path.join(td, name + "-ext.img")
    sh("truncate", "-s", "64M", ext)
    sh("mke2fs", "-q", "-t", "ext4", "-L", root_label, "-d", rootdir, ext)
    uuid = re.search(r"Filesystem UUID:\s+(\S+)", sh("tune2fs", "-l", ext).stdout).group(1)
    for n, f in ((1, fat), (2, ext)):
        first, _, _ = part_bounds(img, n)
        sh("dd", f"if={f}", f"of={img}", "bs=512", f"seek={first}", "conv=notrunc", "status=none")
    return img, uuid


def restore_root(td, pc_xz):
    """Decompress and partclone-restore the root part; return the restored raw image path."""
    pc = os.path.join(td, "restore.pc"); raw = os.path.join(td, "restored.img")
    with open(pc, "wb") as f:
        subprocess.run(["xz", "-dc", pc_xz], stdout=f, check=True)
    sh("truncate", "-s", "64M", raw)
    sh("partclone.restore", "-C", "-q", "-L", "/dev/null", "-s", pc, "-O", raw)  # -O: a regular file target
    return raw


with tempfile.TemporaryDirectory() as td:
    keys = os.path.join(td, "keys")
    sh(REL, "keygen", "--dir", keys, "--name", "root")
    sh(REL, "keygen", "--dir", keys, "--name", "release")
    check("keygen: private key is mode 0600", (os.stat(keys + "/release.key").st_mode & 0o777) == 0o600)
    again = rel("keygen", "--dir", keys, "--name", "release")
    check("keygen: refuses to overwrite an existing key", again.returncode != 0 and "not overwriting" in again.stderr + again.stdout)
    keys_json = os.path.join(td, "keys.json")
    sh(REL, "sign-keys", "--root-key", keys + "/root.key", "--pub", keys + "/release.pub", "--seq", "7", "--out", keys_json)
    root_pub, rel_pub, rel_key = keys + "/root.pub", keys + "/release.pub", keys + "/release.key"
    check("keys.json signed by the root key", verify(root_pub, keys_json, keys_json + ".sig"))

    # ---- build-ab, amd64, stable ----
    VER = "9.9.9"
    img, src_uuid = make_image(td, "amd", VER)
    img_sha = sha256(img)
    out = os.path.join(td, "rel-amd")
    r = rel("build-ab", "--image", img, "--version", VER, "--release-key", rel_key, "--keys-json", keys_json, "--out", out)
    check("build-ab amd64: exit 0", r.returncode == 0, r.stderr)
    vdir = os.path.join(out, "v" + VER)
    check("build-ab: source image unchanged", sha256(img) == img_sha)
    check("build-ab: out dir holds only vVER (temp raw copy removed)", sorted(os.listdir(out)) == ["v" + VER], str(os.listdir(out)))
    want = {"manifest.json", "manifest.json.sig", "root.ext4.pc.xz", "keys.json", "keys.json.sig"}
    check("build-ab amd64: stable release has exactly the expected files", set(os.listdir(vdir)) == want, str(os.listdir(vdir)))
    man = json.load(open(vdir + "/manifest.json"))
    check("manifest: top-level keys", set(man) == {"schema", "version", "channel", "arch", "layout", "min_updater", "built", "parts"}, str(sorted(man)))
    check("manifest: schema/version/channel/arch/layout/min_updater",
          (man["schema"], man["version"], man["channel"], man["arch"], man["layout"], man["min_updater"]) == (1, VER, "stable", "amd64", 2, 1))
    check("manifest: built is UTC ISO 8601", re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", man["built"]) is not None, man["built"])
    check("manifest: one root part, no bootfiles on amd64", [p["role"] for p in man["parts"]] == ["root"], str(man["parts"]))
    p = man["parts"][0]
    check("manifest part: file, size and sha256 match the asset",
          p["file"] == "root.ext4.pc.xz" and p["size"] == os.path.getsize(vdir + "/root.ext4.pc.xz") and p["sha256"] == sha256(vdir + "/root.ext4.pc.xz"), str(p))
    check("manifest: no PRERELEASE marker on stable", not os.path.exists(vdir + "/PRERELEASE"))
    check("manifest.json signed by the release key", verify(rel_pub, vdir + "/manifest.json", vdir + "/manifest.json.sig"))
    check("manifest.json is not verifiable with the root key", not verify(root_pub, vdir + "/manifest.json", vdir + "/manifest.json.sig"))
    check("keys.json copied and signed by the root key", verify(root_pub, vdir + "/keys.json", vdir + "/keys.json.sig") and sha256(vdir + "/keys.json") == sha256(keys_json))
    tampered = os.path.join(td, "tampered.json")
    with open(vdir + "/manifest.json") as f: txt = f.read()
    with open(tampered, "w") as f: f.write(txt.replace('"version": "9.9.9"', '"version": "9.9.8"'))
    check("tampered manifest fails the signature", not verify(rel_pub, tampered, vdir + "/manifest.json.sig"))
    raw = restore_root(td, vdir + "/root.ext4.pc.xz")
    ver = sh("debugfs", "-R", "cat /usr/share/unitotem/release-version", raw).stdout.strip()
    check("root part restores to the image with its release-version", ver == VER, ver)
    check("root part restores with the neutral label ROOT_NEW", sh("tune2fs", "-l", raw).stdout.count("Filesystem volume name:   ROOT_NEW") == 1)
    restored_uuid = re.search(r"Filesystem UUID:\s+(\S+)", sh("tune2fs", "-l", raw).stdout).group(1)
    check("root part restores with a fresh UUID (not the source UUID)", restored_uuid != src_uuid, restored_uuid)
    sh("e2fsck", "-fn", raw)

    # ---- refusals ----
    bad_ver, _ = make_image(td, "badver", "1.0.0")
    o2 = os.path.join(td, "rel-bad")
    r = rel("build-ab", "--image", bad_ver, "--version", VER, "--release-key", rel_key, "--keys-json", keys_json, "--out", o2)
    check("build-ab: version mismatch refused", r.returncode != 0 and "reports version '1.0.0'" in r.stderr, r.stderr)
    check("build-ab: no release left after a refusal", not os.path.exists(os.path.join(o2, "v" + VER, "manifest.json")))
    check("build-ab: temp raw copy removed after a refusal", sorted(os.listdir(o2)) == ["v" + VER] and os.listdir(os.path.join(o2, "v" + VER)) == [], str(os.listdir(o2)))
    not_a, _ = make_image(td, "notA", VER, root_label="ROOT_B")
    r = rel("build-ab", "--image", not_a, "--version", VER, "--release-key", rel_key, "--keys-json", keys_json, "--out", os.path.join(td, "rel-notA"))
    check("build-ab: partition 2 not ROOT_A refused", r.returncode != 0 and "expected ROOT_A" in r.stderr, r.stderr)

    # ---- build-ab, beta channel ----
    out_b = os.path.join(td, "rel-beta")
    r = rel("build-ab", "--image", img, "--version", VER, "--channel", "beta", "--release-key", rel_key, "--keys-json", keys_json, "--out", out_b)
    check("build-ab beta: exit 0 and PRERELEASE marker written", r.returncode == 0 and os.path.exists(out_b + "/v" + VER + "/PRERELEASE"), r.stderr)
    check("build-ab beta: manifest channel is beta", json.load(open(out_b + "/v" + VER + "/manifest.json"))["channel"] == "beta")

    # ---- build-ab, arm64: root + bootfiles ----
    arm, _ = make_image(td, "arm", VER, arm=True)
    out_a = os.path.join(td, "rel-arm")
    r = rel("build-ab", "--image", arm, "--version", VER, "--arch", "arm64", "--release-key", rel_key, "--keys-json", keys_json, "--out", out_a)
    check("build-ab arm64: exit 0", r.returncode == 0, r.stderr)
    adir = out_a + "/v" + VER
    am = json.load(open(adir + "/manifest.json"))
    check("build-ab arm64: parts are root then bootfiles", [p["role"] for p in am["parts"]] == ["root", "bootfiles"], str(am["parts"]))
    bp = am["parts"][1]
    check("build-ab arm64: bootfiles sha256 and size match the asset",
          bp["file"] == "bootfiles.tar.xz" and bp["sha256"] == sha256(adir + "/bootfiles.tar.xz") and bp["size"] == os.path.getsize(adir + "/bootfiles.tar.xz"))
    listing = sh("sh", "-c", "xz -dc '%s/bootfiles.tar.xz' | tar -tvf -" % adir).stdout
    names = [l.split()[-1] for l in listing.splitlines()]
    check("build-ab arm64: bootfiles contain kernel8.img, initramfs8 and overlays/vc4.dtbo",
          {"./kernel8.img", "./initramfs8", "./overlays/vc4.dtbo"} <= set(names), str(names))
    check("build-ab arm64: bootfiles owned by root (numeric 0/0)", all(l.split()[1] == "0/0" for l in listing.splitlines() if l.strip()), listing)
    check("build-ab arm64: manifest signed", verify(rel_pub, adir + "/manifest.json", adir + "/manifest.json.sig"))

    # ---- build (layout 1) from a parts directory ----
    parts = os.path.join(td, "parts")
    os.makedirs(parts)
    with open(parts + "/parts.manifest", "w") as f: f.write("UNITOTEM_ARCH=amd64\nUNITOTEM_VARIANT=test\n")
    with open(parts + "/root.tar.xz", "wb") as f: f.write(b"R" * 4096)
    with open(parts + "/extra.bin", "wb") as f: f.write(b"E" * 128)
    with open(parts + "/SHA256SUMS", "w") as f: f.write("ignored\n")
    out1 = os.path.join(td, "rel-l1")
    r = rel("build", "--parts", parts, "--version", "2.0.0", "--release-key", rel_key, "--keys-json", keys_json, "--out", out1)
    check("build: exit 0", r.returncode == 0, r.stderr)
    d1 = out1 + "/v2.0.0"
    m1 = json.load(open(d1 + "/manifest.json"))
    check("build: layout defaults to 1, arch from parts.manifest", (m1["layout"], m1["arch"], m1["channel"]) == (1, "amd64", "stable"), str(m1))
    names1 = [p["file"] for p in m1["parts"]]
    check("build: parts are every file of the parts set except SHA256SUMS, sorted", names1 == ["extra.bin", "parts.manifest", "root.tar.xz"], str(names1))
    check("build: part sha256 and size match the copied assets",
          all(p["sha256"] == sha256(os.path.join(d1, p["file"])) and p["size"] == os.path.getsize(os.path.join(d1, p["file"])) for p in m1["parts"]))
    check("build: no SHA256SUMS copied", not os.path.exists(d1 + "/SHA256SUMS"))
    check("build: manifest signed by the release key", verify(rel_pub, d1 + "/manifest.json", d1 + "/manifest.json.sig"))
    check("build: keys.json copied", sha256(d1 + "/keys.json") == sha256(keys_json))
    out1b = os.path.join(td, "rel-l1b")
    r = rel("build", "--parts", parts, "--version", "2.0.1", "--channel", "beta", "--layout", "2", "--release-key", rel_key,
            "--keys-json", keys_json, "--out", out1b)
    m1b = json.load(open(out1b + "/v2.0.1/manifest.json"))
    check("build: --channel beta writes PRERELEASE and --layout is honoured",
          r.returncode == 0 and os.path.exists(out1b + "/v2.0.1/PRERELEASE") and m1b["layout"] == 2)
    nometa = os.path.join(td, "nometa"); os.makedirs(nometa)
    with open(nometa + "/a.bin", "wb") as f: f.write(b"A")
    r = rel("build", "--parts", nometa, "--version", "2.0.2", "--release-key", rel_key, "--keys-json", keys_json, "--out", os.path.join(td, "rel-nometa"))
    check("build: missing parts.manifest refused", r.returncode != 0)

print(f"\n{ok} passed, {fail} failed")
sys.exit(1 if fail else 0)
